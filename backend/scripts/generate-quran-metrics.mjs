/**
 * Generates the compact Quran metrics table used to measure memorization
 * portions exactly: surah names, ayah counts and the letter count of every
 * ayah (diacritics removed, the basmala of ayah 1 excluded except in Al-Fatiha).
 *
 * Source: frontend/src/components/ui/quran.json (full text, one entry per ayah).
 * Output:  backend/src/quran/quran-metrics.data.ts and
 *          frontend/src/utils/quranMetrics.data.ts (identical content).
 *
 * Run: node backend/scripts/generate-quran-metrics.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const quran = JSON.parse(fs.readFileSync(path.join(root, 'frontend/src/components/ui/quran.json'), 'utf8'));
const selector = fs.readFileSync(path.join(root, 'frontend/src/components/ui/quran-selector.tsx'), 'utf8');
const names = JSON.parse(selector.slice(selector.indexOf('['), selector.indexOf(']') + 1));

const surahs = quran.data.surahs;
if (surahs.length !== 114 || names.length !== 114) throw new Error('Expected 114 surahs and 114 names');

const lettersOf = (text) => (text.match(/[ء-غف-يٱ]/g) || []).length;
const BASMALA_WORDS = 4;

const letters = surahs.map((s) =>
  s.ayahs.map((a, i) => {
    let text = a.text.replace(/^﻿/, '');
    if (i === 0 && s.number !== 1 && text.startsWith('بِسْمِ')) {
      text = text.split(/\s+/).slice(BASMALA_WORDS).join(' ');
    }
    return lettersOf(text);
  }),
);

const total = letters.flat().reduce((a, b) => a + b, 0);
const body = `// Generated by backend/scripts/generate-quran-metrics.mjs — do not edit by hand.
export const SURAH_NAMES: string[] = ${JSON.stringify(names)};
/** Letters (without diacritics) of every ayah, by surah. */
export const AYAH_LETTERS: number[][] = ${JSON.stringify(letters)};
export const TOTAL_LETTERS = ${total};
`;
for (const out of ['backend/src/quran/quran-metrics.data.ts', 'frontend/src/utils/quranMetrics.data.ts']) {
  fs.writeFileSync(path.join(root, out), body, 'utf8');
}
console.log(`surahs=${letters.length} ayahs=${letters.flat().length} letters=${total} perThumn=${(total / 480).toFixed(1)}`);
